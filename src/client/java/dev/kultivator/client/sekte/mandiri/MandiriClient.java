package dev.kultivator.client.sekte.mandiri;

import dev.kultivator.Kultivator;
import dev.kultivator.client.disciple.DiscipleScreen;
import dev.kultivator.client.hub.HubCards;
import dev.kultivator.client.hub.HubNav;
import dev.kultivator.client.screen.ui.Glyphs;
import dev.kultivator.sekte.mandiri.api.MandiriIds;
import dev.kultivator.sekte.mandiri.cerita.MandiriPayloads;
import net.fabricmc.fabric.api.client.networking.v1.ClientPlayConnectionEvents;
import net.fabricmc.fabric.api.client.networking.v1.ClientPlayNetworking;
import net.fabricmc.fabric.api.client.rendering.v1.hud.HudElementRegistry;
import net.fabricmc.fabric.api.client.rendering.v1.hud.VanillaHudElements;
import net.minecraft.resources.Identifier;
import org.jetbrains.annotations.Nullable;

import java.util.HashMap;
import java.util.Map;

/**
 * Murid Mandiri on the client (DESIGN 39 + 39.F): the one client entry of the six modules, called once from
 * {@code SekteContentClient.init} (wave W0). Module 39E registers here:
 * <ul>
 * <li>the receivers of its four server-to-client payloads ({@code mandiri_harian} the diary page, {@code mandiri_papan}
 * the board, {@code mandiri_pikir} a thought bubble, {@code mandiri_toast} a notice card);</li>
 * <li>the "Jalan Hidup" tab of the disciple scroll ({@link JalanHidupTab}, the third extra tab after P's Hati and R's
 * Hubungan; {@code DiscipleScreen.MAX_EXTRA_TABS} is 3);</li>
 * <li>the hub card {@code sekte_mandiri_jalan} in section MURID ({@link MandiriBoardScreen});</li>
 * <li>the notice cards in the top-right corner of the HUD ({@link ToastMandiri}, before the chat layer);</li>
 * <li>the thought bubbles over disciples ({@link GelembungMandiri});</li>
 * <li>the props 100-129, clips 200-249 and effect hooks of the Gerak system ({@link MandiriPoses}).</li>
 * </ul>
 * The feud module's client entry {@link dev.kultivator.client.sekte.mandiri.seteru.SeteruClient} is called from here
 * (schedule matrix row 11), so 39F never edits this file. Client code reads only the payload records and the shared
 * constants of {@code sekte.mandiri.api} (both common code); it never calls server logic.
 */
public final class MandiriClient {

	/** The images of the module (generated by {@code tools/gen_mandiri_tekstur.py}). */
	public static final Identifier ATLAS_JALAN = Kultivator.id("textures/sekte/mandiri/jalan.png");
	public static final Identifier ATLAS_KEGIATAN = Kultivator.id("textures/sekte/mandiri/kegiatan.png");
	public static final Identifier ATLAS_SUASANA = Kultivator.id("textures/sekte/mandiri/suasana.png");
	public static final Identifier ATLAS_DORONG = Kultivator.id("textures/sekte/mandiri/dorongan.png");
	public static final Identifier KERTAS = Kultivator.id("textures/sekte/mandiri/kertas.png");
	public static final Identifier HIASAN = Kultivator.id("textures/sekte/mandiri/hiasan.png");

	private static final Map<String, MandiriPayloads.Harian> HALAMAN = new HashMap<>();
	private static long versi;
	private static boolean initialised;

	public static void init() {
		if (initialised) {
			return;
		}
		initialised = true;
		ClientPlayNetworking.registerGlobalReceiver(MandiriPayloads.Harian.TYPE, (payload, context) -> terimaHalaman(payload));
		ClientPlayNetworking.registerGlobalReceiver(MandiriPayloads.Papan.TYPE, (payload, context) -> MandiriBoardScreen.terima(payload.data()));
		ClientPlayNetworking.registerGlobalReceiver(MandiriPayloads.Pikir.TYPE, (payload, context) -> GelembungMandiri.terima(payload));
		ClientPlayNetworking.registerGlobalReceiver(MandiriPayloads.Toast.TYPE, (payload, context) -> ToastMandiri.terima(payload));
		ClientPlayConnectionEvents.DISCONNECT.register((handler, client) -> bersih());

		DiscipleScreen.addExtraTab(Glyphs.JALAN, JalanHidupTab::new);
		HubCards.register(HubNav.MURID, MandiriIds.KARTU_JALAN, Glyphs.JALAN, null, MandiriBoardScreen::buka);
		HudElementRegistry.attachElementBefore(VanillaHudElements.CHAT, Kultivator.id("mandiri_toast"), new ToastMandiri());
		GelembungMandiri.init();
		MandiriPoses.init();

		// 39F Perseteruan antar-sekte (title card, feud screen, poses 57-60):
		dev.kultivator.client.sekte.mandiri.seteru.SeteruClient.init();
	}

	/** Sends a button press ({@code AksiMandiri} on the server checks everything again). */
	public static void aksi(String op, String soul, String arg, int n) {
		MandiriPayloads.Aksi payload = new MandiriPayloads.Aksi(op, soul == null ? "" : soul, arg == null ? "" : arg, n);
		if (ClientPlayNetworking.canSend(payload.type())) {
			ClientPlayNetworking.send(payload);
		}
	}

	/** Asks for the diary page of {@code soul}. */
	public static void mintaHalaman(String soul) {
		if (soul != null && !soul.isEmpty()) {
			aksi("harian", soul, "", 0);
		}
	}

	/** The last diary page of {@code soul}, or null. */
	public static @Nullable MandiriPayloads.Harian halaman(String soul) {
		return soul == null ? null : HALAMAN.get(soul);
	}

	/** Grows with every page that arrives. */
	public static long versi() {
		return versi;
	}

	private static void terimaHalaman(MandiriPayloads.Harian page) {
		String soul = page.data().getStringOr("soul", "");
		if (soul.isEmpty()) {
			return;
		}
		if (HALAMAN.size() > 48 && !HALAMAN.containsKey(soul)) {
			HALAMAN.clear();
		}
		HALAMAN.put(soul, page);
		versi++;
		BukuHarianScreen.segarkan(soul);
		if (page.data().getBooleanOr("buka", false)) {
			// "/kultivasi perguruan mandiri harian <murid>": open the book without asking again
			BukuHarianScreen.bukaTanpaMinta(soul, net.minecraft.client.Minecraft.getInstance().gui.screen());
		}
	}

	private static void bersih() {
		HALAMAN.clear();
		versi++;
		GelembungMandiri.bersih();
		ToastMandiri.bersih();
		MandiriBoardScreen.bersih();
	}

	private MandiriClient() {
	}
}
