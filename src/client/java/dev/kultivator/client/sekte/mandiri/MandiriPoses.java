	/** Forward unit vector of the body (x, z). */
	private static double[] depan(DiscipleRenderState st) {
		float yaw = st.bodyRot * Mth.DEG_TO_RAD;
		return new double[]{-Mth.sin(yaw), Mth.cos(yaw)};
	}

	private static ClientLevel level(LivingEntity e) {
		return !EffectQuality.minimal() && e.level() instanceof ClientLevel level ? level : null;
	}

	private static double sebar(RandomSource r, double d) {
		return (r.nextDouble() - 0.5D) * 2.0D * d;
	}

	private static void asap(LivingEntity e, DiscipleRenderState st, float t) {
		ClientLevel level = level(e);
		if (level == null) {
			return;
		}
		RandomSource r = level.getRandom();
		double[] f = depan(st);
		double x = e.getX() + f[0] * 0.62D;
		double y = e.getY() + 0.45D;
		double z = e.getZ() + f[1] * 0.62D;
		int n = EffectQuality.scale(2);
		for (int i = 0; i < n; i++) {
			level.addParticle(new QiParticleOptions(QiParticles.QI_SMOKE, 0xD8D4CC, 0xA8A49C, 0x6E6A64, 0.18F, 0.42F, 36 + r.nextInt(18), 0.0F,
					0.03F, 0.0F, (byte) 0), x + sebar(r, 0.08D), y, z + sebar(r, 0.08D), 0.0D, 0.03D, 0.0D);
		}
		if (r.nextInt(3) == 0) {
			level.addParticle(new QiParticleOptions(QiParticles.QI_FLAME, 0xFFF0B0, 0xFF9030, 0xC03010, 0.06F, 0.01F, 10 + r.nextInt(6), 0.0F,
					0.02F, 0.0F, QiParticleOptions.GLOW), x + sebar(r, 0.1D), e.getY() + 0.12D, z + sebar(r, 0.1D), 0.0D, 0.02D, 0.0D);
		}
	}

	private static void busur(LivingEntity e, DiscipleRenderState st, float t) {
		ClientLevel level = level(e);
		if (level == null) {
			return;
		}
		RandomSource r = level.getRandom();
		double[] f = depan(st);
		double sideX = f[1];
		double sideZ = -f[0];
		int n = EffectQuality.scale(7);
		for (int i = 0; i < n; i++) {
			double a = (i / (double) Math.max(1, n - 1) - 0.5D) * Math.PI * 0.8D;
			double reach = 1.05D;
			double px = e.getX() + f[0] * reach * Math.cos(a) + sideX * reach * Math.sin(a);
			double pz = e.getZ() + f[1] * reach * Math.cos(a) + sideZ * reach * Math.sin(a);
			double py = e.getY() + 1.15D - 0.35D * Math.sin(a);
			level.addParticle(new QiParticleOptions(QiParticles.QI_SPARK, 0xFFFFFF, 0xCFE8FF, 0x6FA8E0, 0.05F, 0.01F, 6 + r.nextInt(4), 0.0F, 0.0F,
					0.0F, QiParticleOptions.GLOW), px, py, pz, sideX * 0.04D * Math.cos(a), 0.01D, sideZ * 0.04D * Math.cos(a));
		}
	}

	private static void batuOrbit(LivingEntity e, DiscipleRenderState st, float t) {
		ClientLevel level = level(e);
		if (level == null) {
			return;
		}
		double cx = e.getX();
		double cy = e.getY() + 0.75D;
		double cz = e.getZ();
		double base = (st.ageInTicks * 0.08D) % (Math.PI * 2.0D);
		int per = EffectQuality.maximal() ? 2 : 1;
		for (int i = 0; i < 4; i++) {
			for (int k = 0; k < per; k++) {
				double a = base + i * Math.PI * 0.5D + k * 0.25D;
				double rad = 0.62D;
				double px = cx + Math.cos(a) * rad;
				double pz = cz + Math.sin(a) * rad;
				// tangential drift with a pull toward the dantian
				double vx = -Math.sin(a) * 0.05D - Math.cos(a) * 0.02D;
				double vz = Math.cos(a) * 0.05D - Math.sin(a) * 0.02D;
				int c = WARNA_BATU[i];
				level.addParticle(new QiParticleOptions(QiParticles.QI, 0xFFFFFF, c, (c >> 1) & 0x7F7F7F, 0.07F, 0.02F, 24, 0.0F, 0.0F,
						0.0F, QiParticleOptions.GLOW), px, cy + Math.sin(a * 2.0D) * 0.08D, pz, vx, 0.0D, vz);
			}
		}
	}

