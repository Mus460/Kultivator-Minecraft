	private static void put(int id, String nama) {
		NAMA[id] = nama;
		BY_NAME.put(nama, id);
	}

	/** True for an index defined here (1-88). 100-199 are defined by their owners' client catalogs. */
	public static boolean ada(int id) {
		return id > 0 && id < NAMA.length;
	}

	/** The canonical name, or null. */
	public static @Nullable String nama(int id) {
		return ada(id) ? NAMA[id] : null;
	}

	/** The index of a name (case-insensitive, or a plain number), or 0. */
	public static int id(@Nullable String nama) {
		if (nama == null || nama.isEmpty()) {
			return TIDAK_ADA;
		}
		String key = nama.trim().toLowerCase(Locale.ROOT);
		Integer id = BY_NAME.get(key);
		if (id != null) {
			return id;
		}
		try {
			int n = Integer.parseInt(key);
			return n > 0 && n <= MAKS ? n : TIDAK_ADA;
		} catch (NumberFormatException e) {
			return TIDAK_ADA;
		}
	}

	/**
	 * The item model path (namespace {@code kultivator}) of a prop defined here: {@code fx/tempat/<name>} (1-40),
	 * {@code fx/tempat/tema/<name>} (41-62), {@code fx/sosok/<name>} (63-88); null otherwise (39 and later 38 props are
	 * registered with their own model ids).
	 */
	public static @Nullable String jalurModel(int id) {
		String nama = nama(id);
		if (nama == null) {
			return null;
		}
		if (id <= TEMPAT_LAST) {
			return "fx/tempat/" + nama;
		}
		return id <= TEMA_LAST ? "fx/tempat/tema/" + nama : "fx/sosok/" + nama;
	}

	/** Packs the synced {@code DATA_PROP} value from right hand, left hand and back (each clamped to 0-1023). */
	public static int pack(int kanan, int kiri, int punggung) {
		return slot(kanan) | slot(kiri) << 10 | slot(punggung) << 20;
	}

	public static int kanan(int data) {
		return data & MAKS;
	}

	public static int kiri(int data) {
		return data >>> 10 & MAKS;
	}

	public static int punggung(int data) {
		return data >>> 20 & MAKS;
	}

	private static int slot(int id) {
		return Math.max(0, Math.min(MAKS, id));
	}

	/** Lang key of a prop name ({@code kultivator.sosok.prop.<id>}, fragment {@code sosok}, 40I). */
	public static String kunciLang(int id) {
		return "kultivator.sosok.prop." + id;
	}

