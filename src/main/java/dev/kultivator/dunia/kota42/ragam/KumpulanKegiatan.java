/**
 * The activity pools of every role (DESIGN 42.4A.3), the micro interludes (42.4A.5) and the spontaneous turns (42.4A.6),
 * read from {@code data/kultivator/tempat/ragam/peran/*.json}, {@code tempat/ragam/selingan.json} and
 * {@code tempat/ragam/belokan.json} (generated by 42S-R's {@code gen_ragam.py}, which validates every clip, prop and titik
 * name). A pool belongs to role ids ({@code "peran"}), schedule groups ({@code "kelompok"}), a themed town ({@code "tema"})
 * or everyone ({@code "umum": true}, the free/meal/evening activities of every adult). Clip and prop names are those of
 * {@link GerakId}/{@link PropId}; a {@code kota42_} prefix names 350-469 / 170-239 ({@link KotaGerakId}); clip
 * {@code @peran} means "the role's own work" (the round decides, so the shop keeps its calls and trades). An unknown name
 * drops that activity with a warning.
 */
public final class KumpulanKegiatan extends SimplePreparableReloadListener<KumpulanKegiatan.Data> {

	public static final Identifier ID = Kultivator.id("kota_ragam_kegiatan");
	private static final FileToIdConverter PERAN = FileToIdConverter.json("tempat/ragam/peran");
	private static final Identifier SELINGAN = Kultivator.id("tempat/ragam/selingan.json");
	private static final Identifier BELOKAN = Kultivator.id("tempat/ragam/belokan.json");

	/** The blocks of a role's day an activity can fill (42.4A.4). */
	public enum Blok {
		KERJA, BEBAS, MAKAN, MALAM;

		private static final Blok[] ALL = values();

		public String id() {
			return name().toLowerCase(Locale.ROOT);
		}

		public static @Nullable Blok dari(String id) {
			for (Blok b : ALL) {
				if (b.id().equals(id)) {
					return b;
				}
			}
			return null;
		}

		/** {@code kultivator.kota.ragam2.blok.<id>}. */
		public String kunciLang() {
			return "kultivator.kota.ragam2.blok." + id();
		}
	}

	/**
	 * When an activity may be planned.
	 *
	 * @param musim     season bit mask (bit {@code Jadwal.SEMI..DINGIN}; 0 = any)
	 * @param hari      week-day bit mask (bit 0-6; 0 = any)
	 * @param jamDari   first hour (-1 = any)
	 * @param jamSampai last hour, inclusive
	 * @param cuaca     0 any, 1 dry weather only, 2 rain only
	 * @param kebiasaan habits of which one is required (empty = none required)
	 */
	public record Syarat(int musim, int hari, int jamDari, int jamSampai, int cuaca, List<String> kebiasaan) {
		public static final Syarat BEBAS = new Syarat(0, 0, -1, -1, 0, List.of());

		public boolean musim(int m) {
			return musim == 0 || (musim >> m & 1) != 0;
		}

		public boolean hari(int pekan) {
			return hari == 0 || (hari >> pekan & 1) != 0;
		}

		/** True when the hour range overlaps {@code [dari, sampai]} (hours 0-23; a range may wrap past midnight). */
		public boolean jam(int dari, int sampai) {
			if (jamDari < 0) {
				return true;
			}
			for (int h = dari; ; h = (h + 1) % 24) {
				if (h >= jamDari && h <= jamSampai) {
					return true;
				}
				if (h == sampai) {
					return false;
				}
			}
		}
	}

	/**
	 * One activity of a pool.
	 *
	 * @param ikutPeran clip {@code @peran}: at runtime the round's own work stands (core work of a mixed group's role)
	 * @param durMin    shortest planned stay, world minutes
	 * @param tanda     tags ({@code inti}, {@code sosial}, {@code jarang}, {@code sendiri}, {@code luar}, {@code teduh},
	 *                  {@code berat}, {@code pasar}, {@code di_tempat}...; 42.4A.3/42.4A.4)
	 */
	public record Aktivitas(String pool, String id, String kunci, Blok blok, String tujuan, int klip, boolean ikutPeran, int varian,
			int kanan, int kiri, int punggung, int jalan, int durMin, int durMax, double bobot, Set<String> tanda, Syarat syarat,
			List<String> selingan) {

		public boolean ada(String tag) {
			return tanda.contains(tag);
		}

		/** Core work of the role (counts toward the >= 50 % of work time). */
		public boolean inti() {
			return tanda.contains("inti");
		}

		/** The 38 activity this plans ({@link Kegiatan} with the pool's goal, clip and props). */
		public Kegiatan kegiatan() {
			return new Kegiatan(kunci, tujuan, klip, varian, kanan, kiri, punggung, jalan, false);
		}

		/**
		 * A stable signature of what the activity looks like (key, clip, variant): repeats, yesterday's penalty, metrics and
		 * plan similarity count two entries that look the same (a chat at the well, a chat at the corner) as one activity.
		 */
		public int sig() {
			return (ikutPeran ? "peran:" + kunci : kunci + ":" + klip + ":" + varian).hashCode();
		}
	}

	/** One pool file. */
	public record Kumpulan(String nama, List<String> peran, List<String> kelompok, String tema, boolean umum, List<Aktivitas> kegiatan) {
	}

	/**
	 * A micro interlude (42.4A.5).
	 *
	 * @param tick  length in ticks
	 * @param sifat weight slope per 100 points of a trait letter (HEXACO)
	 * @param lelah weight factor after two hours of work
	 * @param panas weight factor in summer or heavy work
	 * @param aksi  {@code klip}, {@code tatap} (glance at a passing player), {@code sapa} (turn to a neighbour or child and
	 *              gesture), {@code siul} (a whistled line with the 73 murmur)
	 * @param perlu {@code pemain}, {@code tetangga}, {@code anak} or "" (needed nearby)
	 */
	public record SelinganDef(String id, int klip, int varian, int kanan, int kiri, int tick, double bobot, Map<Character, Double> sifat,
			double lelah, double panas, Set<String> tanda, String aksi, String perlu) {

		/** {@code kultivator.kota.ragam2.selingan.<id>}. */
		public String kunciLang() {
			return "kultivator.kota.ragam2.selingan." + id;
		}
	}

	/**
	 * A spontaneous turn (42.4A.6).
	 *
	 * @param depan     stand two blocks in front of the stall titik, facing it
	 * @param untuk     {@code semua}, {@code dewasa} or {@code anak}
	 * @param kebiasaan habits that triple the weight
	 * @param sahabat   only when a friend (SAHABAT) lives in the place
	 * @param kerumunan joins a crowd (a show): only while the titik's crowd has room
	 * @param musim     season mask (0 = any)
	 */
	public record BelokanDef(String id, String kunci, String titik, boolean depan, int klip, int kanan, int kiri, int durMin, int durMax,
			double bobot, String untuk, List<String> kebiasaan, boolean sahabat, boolean kerumunan, int musim) {

		public Kegiatan kegiatan(String tujuan) {
			return new Kegiatan(kunci, tujuan, klip, 0, kanan, kiri, 0, GerakId.JALAN_SANTAI, false);
		}

		/** {@code kultivator.kota.ragam2.belokan.<id>}. */
		public String kunciLang() {
			return "kultivator.kota.ragam2.belokan." + id;
		}
	}

	/** Everything read at the last reload. */
	public record Data(List<Kumpulan> kumpulan, List<SelinganDef> selingan, Map<String, SelinganDef> selinganId, List<BelokanDef> belokan) {
		public static final Data KOSONG = new Data(List.of(), List.of(), Map.of(), List.of());

		public int jumlahKegiatan() {
			int n = 0;
			for (Kumpulan k : kumpulan) {
				n += k.kegiatan().size();
			}
			return n;
		}
	}

	private static volatile Data data = Data.KOSONG;
	private static final Map<String, List<Aktivitas>> CACHE = new ConcurrentHashMap<>();
	private static boolean registered;

	static void register() {
		if (registered) {
			return;
		}
		registered = true;
		ResourceLoader.get(PackType.SERVER_DATA).registerReloadListener(ID, new KumpulanKegiatan());
	}

	public static Data data() {
		return data;
	}

	/**
	 * The activities a resident of role {@code peran} living in a place of kind {@code jenisTempat} may plan in block
	 * {@code blok}: the role's own pool (else its schedule group's), the themed town's pool (by place kind or the role's
	 * theme), and for adults the common pools of free, meal and evening time. A cached list (cleared on reload).
	 */
	public static List<Aktivitas> untuk(NpcRole peran, String jenisTempat, Blok blok) {
		String tema = jenisTempat.startsWith("kota_tema/") ? jenisTempat.substring(10) : peran.tema != null ? peran.tema : "";
		return CACHE.computeIfAbsent(peran.id() + "|" + tema + "|" + blok.id(), key -> susun(peran, tema, blok));
	}

	private static List<Aktivitas> susun(NpcRole peran, String tema, Blok blok) {
		Data d = data;
		Kumpulan sendiri = null;
		Kumpulan kelompok = null;
		List<Kumpulan> ikut = new ArrayList<>();
		for (Kumpulan k : d.kumpulan()) {
			if (k.peran().contains(peran.id())) {
				sendiri = k;
			} else if (k.kelompok().contains(peran.kelompok.id())) {
				kelompok = k;
			} else if (!tema.isEmpty() && tema.equals(k.tema())) {
				ikut.add(k);
			} else if (k.umum() && blok != Blok.KERJA && peran.kelompok != NpcRole.Kelompok.ANAK) {
				ikut.add(k);
			}
		}
		List<Aktivitas> out = new ArrayList<>();
		Kumpulan utama = sendiri != null ? sendiri : kelompok;
		if (utama != null) {
			ikut.addFirst(utama);
		}
		if (sendiri != null && kelompok != null && blok != Blok.KERJA) {
			// a role with its own pool still enjoys its group's free time (a cook is a worker after hours)
			ikut.add(kelompok);
		}
		for (Kumpulan k : ikut) {
			for (Aktivitas a : k.kegiatan()) {
				if (a.blok() == blok && !out.contains(a)) {
					out.add(a);
				}
			}
		}
		return List.copyOf(out);
	}

	// ================================================================== reload

	@Override
	protected Data prepare(ResourceManager manager, ProfilerFiller profiler) {
		List<Kumpulan> pools = new ArrayList<>();
		Map<Identifier, Resource> files = new TreeMap<>(PERAN.listMatchingResources(manager));
		for (Map.Entry<Identifier, Resource> file : files.entrySet()) {
			Identifier id = PERAN.fileToId(file.getKey());
			if (!Kultivator.MOD_ID.equals(id.getNamespace())) {
				continue;
			}
			JsonObject root = json(file.getValue());
			if (root != null) {
				pools.add(kumpulan(id.getPath(), root));
			}
		}
		List<SelinganDef> sel = new ArrayList<>();
		Map<String, SelinganDef> selId = new LinkedHashMap<>();
		JsonObject s = json(manager.getResource(SELINGAN));
		if (s != null && s.has("selingan")) {
			for (JsonElement e : s.getAsJsonArray("selingan")) {
				SelinganDef def = selingan(e.getAsJsonObject());
				if (def != null) {
					sel.add(def);
					selId.put(def.id(), def);
				}
			}
		}
		List<BelokanDef> bel = new ArrayList<>();
		JsonObject b = json(manager.getResource(BELOKAN));
		if (b != null && b.has("belokan")) {
			for (JsonElement e : b.getAsJsonArray("belokan")) {
				BelokanDef def = belokan(e.getAsJsonObject());
				if (def != null) {
					bel.add(def);
				}
			}
		}
		return new Data(List.copyOf(pools), List.copyOf(sel), Map.copyOf(selId), List.copyOf(bel));
	}

	@Override
	protected void apply(Data prepared, ResourceManager manager, ProfilerFiller profiler) {
		data = prepared;
		CACHE.clear();
	}

	private static @Nullable JsonObject json(Optional<Resource> resource) {
		return resource.map(KumpulanKegiatan::json).orElse(null);
	}

	private static @Nullable JsonObject json(Resource resource) {
		try (Reader reader = resource.openAsReader()) {
			JsonElement root = JsonParser.parseReader(reader);
			return root.isJsonObject() ? root.getAsJsonObject() : null;
		} catch (Exception e) {
			Kultivator.LOGGER.warn("Ragam data {} could not be read", resource.sourcePackId(), e);
			return null;
		}
	}

	private static Kumpulan kumpulan(String nama, JsonObject o) {
		List<Aktivitas> list = new ArrayList<>();
		if (o.has("kegiatan")) {
			for (JsonElement e : o.getAsJsonArray("kegiatan")) {
				Aktivitas a = aktivitas(nama, e.getAsJsonObject());
				if (a != null) {
					list.add(a);
				}
			}
		}
		return new Kumpulan(nama, teksDaftar(o, "peran"), teksDaftar(o, "kelompok"), teks(o, "tema", ""),
				o.has("umum") && o.get("umum").getAsBoolean(), List.copyOf(list));
	}

	private static @Nullable Aktivitas aktivitas(String pool, JsonObject o) {
		String id = teks(o, "id", "");
		Blok blok = Blok.dari(teks(o, "blok", ""));
		String klipNama = teks(o, "klip", "");
		boolean ikut = "@peran".equals(klipNama);
		int klip = ikut ? 0 : klip(klipNama);
		int jalan = klip(teks(o, "jalan", ""));
		int kanan = prop(teks(o, "kanan", ""));
		int kiri = prop(teks(o, "kiri", ""));
		int punggung = prop(teks(o, "punggung", ""));
		if (id.isEmpty() || blok == null || klip < 0 || jalan < 0 || kanan < 0 || kiri < 0 || punggung < 0) {
			Kultivator.LOGGER.warn("Ragam pool {}: activity {} dropped (unknown blok, clip or prop)", pool, id);
			return null;
		}
		int[] dur = {20, 60};
		if (o.has("durasi")) {
			JsonArray d = o.getAsJsonArray("durasi");
			dur[0] = Math.max(5, d.get(0).getAsInt());
			dur[1] = Math.max(dur[0], d.get(1).getAsInt());
		}
		return new Aktivitas(pool, id, teks(o, "kunci", "rg_" + id), blok, teks(o, "tujuan", "@tetap"), klip, ikut,
				o.has("varian") ? Math.max(0, Math.min(GerakId.VARIAN_MAKS, o.get("varian").getAsInt())) : 0, kanan, kiri, punggung,
				jalan, dur[0], dur[1], o.has("bobot") ? o.get("bobot").getAsDouble() : 1.0D, Set.copyOf(teksDaftar(o, "tanda")),
				syarat(o.has("syarat") ? o.getAsJsonObject("syarat") : null), teksDaftar(o, "selingan"));
	}

	private static Syarat syarat(@Nullable JsonObject o) {
		if (o == null) {
			return Syarat.BEBAS;
		}
		int musim = musim(teksDaftar(o, "musim"));
		int hari = 0;
		if (o.has("hari")) {
			for (JsonElement e : o.getAsJsonArray("hari")) {
				hari |= 1 << Math.floorMod(e.getAsInt(), 7);
			}
		}
		int dari = -1;
		int sampai = -1;
		if (o.has("jam")) {
			JsonArray j = o.getAsJsonArray("jam");
			dari = Math.floorMod(j.get(0).getAsInt(), 24);
			sampai = Math.floorMod(j.get(1).getAsInt(), 24);
		}
		String c = teks(o, "cuaca", "");
		return new Syarat(musim, hari, dari, sampai, c.equals("cerah") ? 1 : c.equals("hujan") ? 2 : 0, teksDaftar(o, "kebiasaan"));
	}

	private static int musim(List<String> names) {
		int mask = 0;
		for (String m : names) {
			switch (m) {
				case "semi" -> mask |= 1;
				case "panas" -> mask |= 2;
				case "gugur" -> mask |= 4;
				case "dingin" -> mask |= 8;
				default -> Kultivator.LOGGER.warn("Ragam data: unknown season {}", m);
			}
		}
		return mask;
	}

	private static @Nullable SelinganDef selingan(JsonObject o) {
		String id = teks(o, "id", "");
		int klip = klip(teks(o, "klip", ""));
		int kanan = prop(teks(o, "kanan", ""));
		int kiri = prop(teks(o, "kiri", ""));
		if (id.isEmpty() || klip < 0 || kanan < 0 || kiri < 0) {
			Kultivator.LOGGER.warn("Ragam interlude {} dropped (unknown clip or prop)", id);
			return null;
		}
		Map<Character, Double> sifat = new HashMap<>();
		if (o.has("sifat")) {
			for (Map.Entry<String, JsonElement> e : o.getAsJsonObject("sifat").entrySet()) {
				if (!e.getKey().isEmpty()) {
					sifat.put(Character.toUpperCase(e.getKey().charAt(0)), e.getValue().getAsDouble());
				}
			}
		}
		return new SelinganDef(id, klip, o.has("varian") ? o.get("varian").getAsInt() : 0, kanan, kiri,
				o.has("tick") ? Math.max(10, Math.min(80, o.get("tick").getAsInt())) : 30, o.has("bobot") ? o.get("bobot").getAsDouble() : 1.0D,
				Map.copyOf(sifat), o.has("lelah") ? o.get("lelah").getAsDouble() : 1.0D, o.has("panas") ? o.get("panas").getAsDouble() : 1.0D,
				Set.copyOf(teksDaftar(o, "tanda")), teks(o, "aksi", "klip"), teks(o, "perlu", ""));
	}

	private static @Nullable BelokanDef belokan(JsonObject o) {
		String id = teks(o, "id", "");
		int klip = klip(teks(o, "klip", ""));
		int kanan = prop(teks(o, "kanan", ""));
		int kiri = prop(teks(o, "kiri", ""));
		if (id.isEmpty() || klip < 0 || kanan < 0 || kiri < 0) {
			Kultivator.LOGGER.warn("Ragam turn {} dropped (unknown clip or prop)", id);
			return null;
		}
		int[] dur = {5, 10};
		if (o.has("dur")) {
			JsonArray d = o.getAsJsonArray("dur");
			dur[0] = Math.max(2, d.get(0).getAsInt());
			dur[1] = Math.max(dur[0], d.get(1).getAsInt());
		}
		return new BelokanDef(id, teks(o, "kunci", "rg_belok_" + id), teks(o, "titik", "kursi"), o.has("depan") && o.get("depan").getAsBoolean(),
				klip, kanan, kiri, dur[0], dur[1], o.has("bobot") ? o.get("bobot").getAsDouble() : 1.0D, teks(o, "untuk", "semua"),
				teksDaftar(o, "kebiasaan"), o.has("sahabat") && o.get("sahabat").getAsBoolean(),
				o.has("kerumunan") && o.get("kerumunan").getAsBoolean(), musim(teksDaftar(o, "musim")));
	}

	// ================================================================== names

	/** Clip id by name ("" = 0; {@code kota42_} prefix = 350-459); -1 when unknown. */
	static int klip(String name) {
		if (name.isEmpty()) {
			return 0;
		}
		int id = name.startsWith("kota42_") ? KotaGerakId.klipId(name) : GerakId.id(name);
		if (id <= 0) {
			Kultivator.LOGGER.warn("Ragam data: unknown clip {}", name);
			return -1;
		}
		return id;
	}

	/** Prop id by name ("" = 0; {@code kota42_} prefix = 170-239); -1 when unknown. */
	static int prop(String name) {
		if (name.isEmpty()) {
			return 0;
		}
		if (name.startsWith("kota42_")) {
			String key = name.substring(7);
			for (int id = KotaGerakId.PROP_FIRST; id <= KotaGerakId.PROP_LAST; id++) {
				if (key.equals(KotaGerakId.propNama(id))) {
					return id;
				}
			}
		} else {
			int id = PropId.id(name);
			if (id > 0) {
				return id;
			}
		}
		Kultivator.LOGGER.warn("Ragam data: unknown prop {}", name);
		return -1;
	}

	private static String teks(JsonObject o, String key, String fallback) {
		return o.has(key) && o.get(key).isJsonPrimitive() ? o.get(key).getAsString() : fallback;
	}

	private static List<String> teksDaftar(JsonObject o, String key) {
		if (!o.has(key) || !o.get(key).isJsonArray()) {
			return List.of();
		}
		List<String> out = new ArrayList<>();
		for (JsonElement e : o.getAsJsonArray(key)) {
			out.add(e.getAsString());
		}
		return List.copyOf(out);
	}
}
