	/** The id of a design name or catalog name (with or without {@code kota42_}), or 0. */
	public static int klipId(@Nullable String nama) {
		if (nama == null) {
			return 0;
		}
		String key = nama.startsWith("kota42_") ? nama.substring(7) : nama;
		for (int i = 0; i < KLIP_NAMA.length; i++) {
			if (KLIP_NAMA[i].equals(key)) {
				return KLIP_FIRST + i;
			}
		}
		return 0;
	}

