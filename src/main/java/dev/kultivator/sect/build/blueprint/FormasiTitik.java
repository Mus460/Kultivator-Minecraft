package dev.kultivator.sect.build.blueprint;

import dev.kultivator.sect.build.api.SectTemplates;
import net.minecraft.world.level.block.Blocks;
import net.minecraft.world.level.block.state.BlockState;
import net.minecraft.world.level.levelgen.structure.BoundingBox;
import org.jetbrains.annotations.Nullable;

import java.util.ArrayList;
import java.util.List;

/**
 * The Titik Formasi plots of the nine ground templates (DESIGN 24.6.2 A, 24.13 item 8): flat paved squares with a carved
 * centre tile where a Mata Formasi goes, added to templates 3-9 through {@link TemplateExtensions} as components
 * {@code t<tier>_formasi_<n>} (so a finished site builds them as "Tambahan", never rebuilding anything). Each plot names
 * an anchor {@code formasi_<n>} one block above its centre tile; {@code EngineApi.formasiAnchors} lists the anchors of the
 * finished plots and {@code requestPattern} lays a formation pattern on one (see {@link PolaPart}).
 * <p>
 * The design table reserves 13 x 13 up to 23 x 23 squares "inside an existing component", but the nine templates were
 * drawn without them and are fully built over, so the squares live where the dry runs of all components of every tier and
 * of every other module's extension (harness {@code FreeSq}) leave a free square: nothing above the floor but lanterns,
 * flowers and low plants (which the pattern's own cells may replace like any light swap), the same zone level under the
 * whole square, off the central axis, the Bagua disc and every named anchor. Radii are the largest of 11, 8, 6, 3 that
 * fit (the table row decides the preferred radius; {@code n} keeps the row of the table: 0 gate tower, 1 Bagua court,
 * 2 alchemy hall, 3 meditation court, 4-6 node plots, 7 Altar Formasi Gabungan). The tier is the table's, raised to the
 * highest tier of any component that paves a cell of the square, and the plot sorts last in its tier, so no later
 * paving ever replaces the carved tile. A template without room for a row simply has no such anchor (templates 3 and 4
 * have none at all). Re-run the harness after changing any template or extension.
 */
public final class FormasiTitik {

	/** One plot: row {@code n}, the tier that builds it, the half size, the centre tile (x, z) and the zone whose level it stands on. */
	public record Plot(int n, int tier, int radius, int x, int z, String zone) {

		/** The anchor id {@code formasi_<n>}. */
		public String id() {
			return "formasi_" + n;
		}

		/** The plot component id (saved forever: never rename). */
		public String componentId() {
			return "t" + tier + "_formasi_" + n;
		}

		/** The id of the pattern component requested on this plot. */
		public String polaId() {
			return "t" + tier + "_pola_" + n;
		}

		public Lv level() {
			return Lv.zone(zone);
		}
	}

	private static final Plot[][] TABLE = new Plot[SectTemplates.COUNT + 1][];

	static {
		for (int t = 0; t <= SectTemplates.COUNT; t++) {
			TABLE[t] = new Plot[0];
		}
		// PLOTS-BEGIN (generated by the FreeSq harness)
		table(5, new Plot(2, 7, 3, -22, 13, "plaza"));
		table(6, new Plot(2, 7, 3, 35, 16, "plaza"));
		table(7, new Plot(0, 7, 3, 30, 24, "court"), new Plot(1, 8, 3, 34, 37, "court"), new Plot(2, 7, 3, 30, -51, "main"),
				new Plot(3, 8, 3, -24, -51, "main"), new Plot(7, 9, 3, 41, 24, "court"));
		table(8, new Plot(0, 7, 3, 37, -11, "east"), new Plot(1, 7, 3, 55, -12, "east"), new Plot(2, 7, 6, 16, -61, "terrace"),
				new Plot(3, 8, 3, -25, -79, "terrace"), new Plot(4, 9, 3, 21, -78, "terrace"), new Plot(5, 9, 3, 21, -6, "east"),
				new Plot(6, 9, 3, -22, 13, "west"), new Plot(7, 9, 6, -15, -61, "terrace"));
		table(9, new Plot(0, 8, 6, -56, 38, "court"), new Plot(1, 7, 3, 35, 41, "court"), new Plot(2, 8, 6, 66, -26, "binatang"),
				new Plot(3, 8, 6, 55, -50, "tetua"), new Plot(4, 9, 3, -68, 40, "court"), new Plot(5, 9, 3, -13, -83, "summit"),
				new Plot(6, 9, 3, 8, 29, "court"), new Plot(7, 9, 8, 39, 27, "court"));
		// PLOTS-END
	}

	private static void table(int template, Plot... plots) {
		TABLE[template] = plots;
	}

	private static boolean registered;

	/** From {@code SectBuild.init}: adds the plot components to templates 3-9 (before the first {@code Templates.get}). */
	public static synchronized void register() {
		if (registered) {
			return;
		}
		registered = true;
		for (int template = 1; template <= SectTemplates.COUNT; template++) {
			if (TABLE[template].length > 0) {
				int t = template;
				TemplateExtensions.register("formasi_titik", t, builder -> add(builder, t));
			}
		}
	}

	/** The plots of ground template {@code template} (empty when it has none). */
	public static List<Plot> plots(int template) {
		return template >= 1 && template <= SectTemplates.COUNT ? List.of(TABLE[template]) : List.of();
	}

	/** The plot named by anchor id {@code anchorId} ({@code formasi_<n>}) in {@code template}, or null. */
	public static @Nullable Plot plot(int template, String anchorId) {
		for (Plot plot : plots(template)) {
			if (plot.id().equals(anchorId)) {
				return plot;
			}
		}
		return null;
	}

	private static void add(TemplateSpec.Builder builder, int template) {
		for (Plot plot : TABLE[template]) {
			if (!builder.hasComponent(plot.componentId())) {
				builder.add(Component.of(plot.componentId(), plot.tier()).kind("formasi_titik").name("formasi_titik").group(Component.Group.ORNAMENT, Integer.MAX_VALUE)
						.add(new TitikPart(plot)));
			}
		}
	}

	/** The paved square: earthwork like {@link Paving}, a stone field, a fret border and the carved centre tile. */
	private static final class TitikPart implements Part {
		private final Plot plot;

		TitikPart(Plot plot) {
			this.plot = plot;
		}

		@Override
		public BoundingBox bounds(Ctx ctx) {
			int y = ctx.level(plot.level());
			return new BoundingBox(plot.x() - plot.radius(), y - 1, plot.z() - plot.radius(), plot.x() + plot.radius(), y, plot.z() + plot.radius());
		}

		@Override
		public String kind() {
			return "formasi_titik";
		}

		@Override
		public void emit(Ctx ctx, Sink sink) {
			int y = ctx.level(plot.level());
			List<Object> claimed = claimed(ctx);
			int r = plot.radius();
			for (int dx = -r; dx <= r; dx++) {
				for (int dz = -r; dz <= r; dz++) {
					int x = plot.x() + dx;
					int z = plot.z() + dz;
					if (!claimedAt(claimed, x, z)) {
						earthwork(ctx, sink, x, z, y);
					}
					sink.phase(Phase.PLINTH).set(x, y - 1, z, floor(dx, dz, r));
				}
			}
			// The anchor is the carved centre tile itself: the Mata Formasi stands on it (one block above).
			sink.anchor(plot.id(), plot.x(), y - 1, plot.z());
		}

		/**
		 * The columns other parts stand on (their boxes, a wall by its segments; ornaments and the plots themselves ignored):
		 * their own earthwork levels that ground, so the plot only grades the free pockets between them.
		 */
		private List<Object> claimed(Ctx ctx) {
			List<Object> boxes = new ArrayList<>();
			for (Component component : ctx.spec().components()) {
				for (Part part : component.parts()) {
					if (part instanceof TitikPart || part instanceof PolaPart || part instanceof Ornament) {
						continue;
					}
					if (part instanceof Wall wall) {
						boxes.add(wall);
						continue;
					}
					BoundingBox box = part.bounds(ctx);
					if (box != null) {
						boxes.add(box);
					}
				}
			}
			return boxes;
		}

		private boolean claimedAt(List<Object> boxes, int x, int z) {
			for (Object each : boxes) {
				if (each instanceof BoundingBox box ? x >= box.minX() && x <= box.maxX() && z >= box.minZ() && z <= box.maxZ()
						: each instanceof Wall wall && wall.near(x, z, 0)) {
					return true;
				}
			}
			return false;
		}

		/** Light levelling of a free column like {@link Paving}: plants and natural ground above the floor go, earth fills up to it. */
		private static void earthwork(Ctx ctx, Sink sink, int x, int z, int y) {
			int ground = ctx.terrain().ground(x, z);
			int top = ctx.terrain().top(x, z);
			sink.phase(Phase.CLEAR);
			for (int cy = Math.max(ground + 1, y); cy <= Math.min(top, y + 6); cy++) {
				sink.air(x, cy, z);
			}
			sink.phase(Phase.CUT);
			for (int cy = y; cy <= Math.min(ground, y + 3); cy++) {
				sink.air(x, cy, z);
			}
			sink.phase(Phase.FILL);
			for (int cy = Math.max(ground + 1, y - 7); cy <= y - 2; cy++) {
				sink.set(x, cy, z, Palette.st(Palette.FILL_EARTH));
			}
		}

		private static BlockState floor(int dx, int dz, int r) {
			int ring = Math.max(Math.abs(dx), Math.abs(dz));
			if (ring == 0) {
				return Palette.st(Blocks.CHISELED_STONE_BRICKS);
			}
			if (ring == r) {
				return Palette.st(Palette.STONE_FRET);
			}
			if (ring == 1 || r >= 6 && ring == r - 2) {
				return Palette.st(Palette.STONE);
			}
			return Palette.st(Palette.AXIS_PAVE);
		}
	}

	private FormasiTitik() {
	}
}
