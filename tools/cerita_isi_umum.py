def isi(g):
    for key, pair in ENGINE.items():
        g.tx('tempat_cerita', key, pair)
    for key, pair in ADEGAN.items():
        g.tx('tempat_cerita', key, pair)
    for tid, (name, title) in TOKOH.items():
        g.tx('tempat_cerita', f'kultivator.cerita.tokoh.{tid}', (name, name))
        g.tx('tempat_cerita', f'kultivator.cerita.tokoh.{tid}.gelar', title)
    for item, (name, lore) in BARANG.items():
        g.tx('tempat_cerita', f'kultivator.cerita.barang.{item}', name)
        g.tx('tempat_cerita', f'kultivator.cerita.barang.{item}.lore', lore)
    g.GELAR.update(GELAR)
    for tid, pair in TEMPAT.items():
        g.tx('tempat_cerita', f'kultivator.cerita.tempat.{tid}', pair)
    for bab, (title, opener) in BAB.items():
        g.tx('tempat_cerita', f'kultivator.cerita.takhta.bab.{bab}', title)
        g.tx('tempat_cerita', f'kultivator.cerita.takhta.bab.{bab}.pembuka', opener)
    for (bab, hasil), pair in HASIL.items():
        g.tx('tempat_cerita', f'kultivator.cerita.takhta.hasil.{bab}.{hasil}', pair)
