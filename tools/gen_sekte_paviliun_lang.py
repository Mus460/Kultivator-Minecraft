def main():
    here = os.path.join(os.path.dirname(__file__), "..", "lang-src")
    for index, lang in ((0, "id_id"), (1, "en_us")):
        data = {k: v[index] for k, v in L.items()}
        with open(os.path.join(here, "sekte_paviliun.%s.json" % lang), "w", encoding="utf-8", newline="\n") as f:
            json.dump(data, f, indent=2, ensure_ascii=False)
            f.write("\n")
    print("sekte_paviliun lang: %d keys" % len(L))


if __name__ == "__main__":
    main()
