def isi(g):
    index = {}
    for grup, situasi in L.items():
        for sit, lines in situasi.items():
            for n, pair in enumerate(lines):
                g.tx('tempat_kalimat', f'kultivator.cerita.kalimat.{grup}.{sit}.{n}', pair)
            index[f'{grup}.{sit}'] = len(lines)
    need = {'pagi', 'siang', 'malam', 'hujan', 'dagang', 'keluhan', 'takut', 'kagum', 'festival', 'buronan'}
    missing = need - set(L['umum'])
    if missing:
        g.ERRORS.append(f'kalimat: umum lacks {sorted(missing)}')
    known = {'umum', 'anak', 'pekerja', 'pedagang', 'penjaga', 'tetua', 'kultivator', 'cendekia', 'rahib', 'pejabat', 'khusus'}
    for grup in L:
        if grup not in known:
            g.ERRORS.append(f'kalimat: unknown group {grup}')
        for sit in L[grup]:
            if sit not in need:
                g.ERRORS.append(f'kalimat: unknown situation {grup}.{sit}')
    return index
